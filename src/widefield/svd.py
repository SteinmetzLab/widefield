# MATLAB's filtfilt pads by 3*(nfilt-1) with an odd reflection. scipy defaults to
# padlen=3*max(len(a), len(b)), which is one sample longer and gives visibly different
# edges — so every filtfilt here passes MATLAB's padlen explicitly.
def _matlab_filtfilt(b: np.ndarray, a: np.ndarray, x: np.ndarray, axis: int = -1) -> np.ndarray:
    padlen = 3 * (max(len(a), len(b)) - 1)
    return filtfilt(b, a, x, axis=axis, padtype="odd", padlen=padlen)


def hp_filt(v: np.ndarray, fs: float, cutoff_freq: float = 0.01) -> np.ndarray:
    """Zero-phase high-pass the temporal components. Port of ``hpFilt.m``.

    3rd-order Butterworth, applied forwards and backwards (``filtfilt``). Useful when some
    components carry a very slow drift that swamps everything else.

    Returns float32, matching the MATLAB's ``single(...)`` cast.
    """
    v = np.asarray(v)
    b, a = butter(3, cutoff_freq / (fs / 2), btype="high")
    return _matlab_filtfilt(b, a, v.astype(np.float64), axis=-1).astype(np.float32)


def detrend_and_filt(v: np.ndarray, fs: float) -> np.ndarray:
    """Linear-detrend, notch out heartbeat, then high-pass. Port of ``detrendAndFilt.m``.

    Note this uses **causal** one-pass filtering (MATLAB ``filter``, not ``filtfilt``), so
    the output is phase-shifted relative to the input. That is what the production hemo
    pipeline applies to ``Vcorr``, so the port keeps it rather than silently "improving" it
    to zero-phase — changing it would shift every downstream latency measurement.
    """
    v = np.asarray(v, dtype=np.float64)
    highpass_cutoff = 0.01  # Hz
    heartbeat_bandstop = (9.0, 14.0)  # Hz

    b_hp, a_hp = butter(2, highpass_cutoff / (fs / 2), btype="high")
    b_heart, a_heart = butter(2, [f / (fs / 2) for f in heartbeat_bandstop], btype="bandstop")

    dv = detrend(v, axis=-1, type="linear")
    fv_heart = lfilter(b_heart, a_heart, dv, axis=-1)
    return lfilter(b_hp, a_hp, fv_heart, axis=-1)


def subsample_shift(v: np.ndarray, p: int, q: int) -> np.ndarray:
    """Delay a time series by ``p/q`` of a sample by linear interpolation.

    Port of ``SubSampleShift.m`` **as merged from cortex-lab's unmerged
    ``SubSampleShift_interp`` branch**: the older implementation used ``resample``, whose
    filtering could put a large error in the final sample that then became a big artifact
    after further filtering. Linear interpolation avoids that, and the original last sample
    is carried through verbatim rather than extrapolated.

    ``v`` is ``(nSV, nTimes)``; the shift is applied along time. Samples that fall past the
    end of the input are NaN (only reachable for ``p/q > 1``), except the very last, which
    is copied from the input.
    """
    v = np.asarray(v, dtype=np.float64)
    if v.ndim != 2:
        raise ValueError(f"V must be (nSV, nTimes); got shape {v.shape}")
    if p <= 0 or q <= 0:
        raise ValueError("p and q must be positive (negative shifts are not supported)")

    n = v.shape[1]
    src = np.arange(n, dtype=np.float64)
    query = src + (p / q)
    out = np.empty_like(v)
    for s in range(v.shape[0]):
        # left/right=nan reproduces interp1's default (no extrapolation).
        out[s] = np.interp(query, src, v[s], left=np.nan, right=np.nan)
    out[:, -1] = v[:, -1]
    return out


