"""SVD-compressed movie primitives.

A widefield movie is stored factored as ``M = U @ V`` (the singular values are folded into
``V``, following the MATLAB convention documented in the top-level README), where

* ``U`` is ``(Ypix, Xpix, nSV)`` — spatial components,
* ``V`` is ``(nSV, nFrames)`` — temporal components.

Everything here is a faithful port of the MATLAB in ``matlab/`` and is validated against
golden reference data generated by ``tests/matlab_ref/gen_reference.m``. Where the MATLAB and
a "more obvious" Python spelling disagree, the MATLAB wins and the difference is commented.

Pure numpy/scipy — no Qt, so this stays importable on a headless machine.
"""

from __future__ import annotations

import numpy as np
from scipy.signal import butter, detrend, filtfilt, lfilter

__all__ = [
    "flatten_u",
    "svd_frame_reconstruct",
    "pixel_timecourse",
    "change_u",
    "dff_from_svd",
    "hp_filt",
    "detrend_and_filt",
    "subsample_shift",
    "bin_image",
]


# --------------------------------------------------------------------------------------
# reshaping helpers
# --------------------------------------------------------------------------------------


def flatten_u(u: np.ndarray) -> np.ndarray:
    """``U`` ``(Ypix, Xpix, nSV)`` → ``(nPix, nSV)``, C-contiguous.

    Contiguity matters: every reconstruction is a GEMM/GEMV against this array, and a strided
    or Fortran-ordered view silently costs a full copy inside BLAS on every call instead of
    once here.

    For a C-contiguous ``u`` (what :func:`widefield.io.read_u_from_npy` returns) this is a free
    reshape — no copy — which is what makes it safe to call per frame.
    """
    u = np.asarray(u)
    if u.ndim != 3:
        raise ValueError(f"U must be (Ypix, Xpix, nSV); got shape {u.shape}")
    ypix, xpix, nsv = u.shape
    flat = u.reshape(ypix * xpix, nsv)
    return flat if flat.flags["C_CONTIGUOUS"] else np.ascontiguousarray(flat)


def _aligned_nsv(u: np.ndarray, v: np.ndarray) -> int:
    """Components shared by U and V.

    The hemo-corrected channel's ``V`` is routinely truncated relative to the blue ``U`` it
    borrows, so callers pass mismatched ranks all the time; MATLAB would error, we truncate.
    """
    return min(u.shape[-1], v.shape[0])


