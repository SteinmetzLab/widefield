# reconstruction
# --------------------------------------------------------------------------------------


def svd_frame_reconstruct(u: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Reconstruct frames from the SVD basis. Port of ``svdFrameReconstruct.m``.

    Parameters
    ----------
    u : (Ypix, Xpix, nSV)
    v : (nSV, nFrames) or (nSV,) for a single frame

    Returns
    -------
    (Ypix, Xpix, nFrames), or (Ypix, Xpix) when ``v`` was 1-D.

    Unlike MATLAB, a trailing singleton is only dropped when ``v`` itself was 1-D — so
    ``v[:, [7]]`` reliably gives you ``(Y, X, 1)`` rather than silently collapsing.
    """
    u = np.asarray(u)
    v = np.asarray(v)
    single = v.ndim == 1
    if single:
        v = v[:, None]
    if v.ndim != 2:
        raise ValueError(f"V must be (nSV, nFrames) or (nSV,); got shape {v.shape}")

    nsv = _aligned_nsv(u, v)
    ypix, xpix = u.shape[0], u.shape[1]
    flat = flatten_u(u[..., :nsv])
    out = (flat @ v[:nsv]).reshape(ypix, xpix, v.shape[1])
    return out[..., 0] if single else out


def pixel_timecourse(u: np.ndarray, v: np.ndarray, pixel: tuple[int, int]) -> np.ndarray:
    """One pixel's full timecourse ``(nFrames,)`` — ``U[y, x, :] @ V``.

    ``pixel`` is ``(row, col)`` and **0-based** (the MATLAB is 1-based). Reconstructing a
    single pixel costs O(nSV * nFrames), never the full movie.
    """
    u = np.asarray(u)
    v = np.asarray(v)
    nsv = _aligned_nsv(u, v)
    y, x = int(pixel[0]), int(pixel[1])
    return np.asarray(u[y, x, :nsv]) @ np.asarray(v[:nsv])


# --------------------------------------------------------------------------------------
# basis changes / dF/F
# --------------------------------------------------------------------------------------


def change_u(u: np.ndarray, v: np.ndarray, new_u: np.ndarray) -> np.ndarray:
    """Re-express the movie ``(u, v)`` in a new spatial basis. Port of ``ChangeU.m``.

    Returns ``new_v`` such that ``new_u @ new_v`` approximates ``u @ v``. Exact only when
    ``new_u`` spans ``u``'s column space; that is the case in practice because the callers
    project between two bases of the same movie.
    """
    u, v, new_u = np.asarray(u), np.asarray(v), np.asarray(new_u)
    flat, new_flat = flatten_u(u), flatten_u(new_u)
    if flat.shape[0] != new_flat.shape[0]:
        raise ValueError(
            f"U and newU must have the same pixel count; got {flat.shape[0]} vs {new_flat.shape[0]}"
        )
    # (new_flat.T @ flat) first: an (nSV, nSV) mixing matrix, then one small matmul against V.
    # Grouping the other way would form an (nPix, nFrames) intermediate — the whole movie.
    return (new_flat.T @ flat) @ v


def dff_from_svd(
    u: np.ndarray, v: np.ndarray, mean_image: np.ndarray, soft_norm: float | None = None
) -> tuple[np.ndarray, np.ndarray]:
    """Soft-normalised dF/F, kept in the original ``U`` basis. Port of ``dffFromSVD.m``.

    Dividing each pixel by (mean + soft) breaks orthonormality of ``U``, so the result is
    re-cast into the original basis via :func:`change_u`; only ``V`` changes.

    ``soft_norm`` defaults to ``median(mean_image)``, as in the MATLAB. It keeps low-mean
    pixels (outside the window, vasculature) from exploding when divided by near-zero.

    Returns ``(new_u, new_v)``. ``new_u`` *is* ``u`` — returned for symmetry with the MATLAB,
    whose two-output signature exists to stop callers using a stale single-output version.
    """
    u, v = np.asarray(u), np.asarray(v)
    mean_image = np.asarray(mean_image)
    nsv = _aligned_nsv(u, v)
    u = u[..., :nsv]
    v = v[:nsv]

    flat = flatten_u(u)
    mean_flat = mean_image.reshape(-1)
    if mean_flat.size != flat.shape[0]:
        raise ValueError(
            f"meanImage has {mean_flat.size} pixels but U has {flat.shape[0]}"
        )

    if soft_norm is None:
        soft_norm = float(np.median(mean_flat))

    # Zero-mean V, then divide U by (mean + soft) and rotate back into the original basis.
    new_v = v - v.mean(axis=1, keepdims=True)
    nonnorm = (flat / (mean_flat[:, None] + soft_norm)).reshape(u.shape)
    return u, change_u(nonnorm, new_v, u)


