def bin_image(image: np.ndarray, bin_factor: int) -> np.ndarray:
    """BxB spatial binning by box-filtering then decimating. Port of ``binImage.m``.

    ``image`` is ``(Ypix, Xpix)`` or ``(Ypix, Xpix, nFrames)``.

    This is deliberately *not* a block mean, and the difference is not cosmetic. The MATLAB
    convolves with a BxB box via ``conv2(..., 'same')`` and then takes every Bth sample
    starting at the first, which averages the window ``[i - (B - 1 - B//2), i + B//2]``:

    * ``B = 2`` — that window *is* the block ``[i, i+1]``, so binning by 2 does coincide with
      a block mean. This is a coincidence of the offset, not the general rule.
    * ``B >= 4`` — the window straddles the neighbouring blocks (for ``B = 4`` it spans
      ``[i-1, i+2]``), so results differ substantially from a block mean, and out-of-range
      samples are treated as **zero** rather than renormalised, which biases the first and
      last row/column low. On the reference image ``B = 4`` gives 7.875 where a block mean
      gives 20.5.

    Output size is ``ceil(N / B)`` per axis: the final row/column is a partial, zero-padded
    window rather than being dropped.

    Faithfulness beats tidiness here — these values feed registration and QC comparisons
    against MATLAB-derived numbers, so the quirk is reproduced rather than fixed.
    """
    image = np.asarray(image)
    bin_factor = int(bin_factor)
    if bin_factor < 1:
        raise ValueError("bin_factor must be >= 1")
    if bin_factor == 1:
        return image.copy()
    squeeze = image.ndim == 2
    if squeeze:
        image = image[:, :, None]
    if image.ndim != 3:
        raise ValueError(f"image must be 2-D or 3-D; got shape {image.shape}")

    kern = np.ones(bin_factor, dtype=np.float64) / bin_factor
    off = bin_factor // 2
    ypix, xpix = image.shape[0], image.shape[1]

    out = []
    for f in range(image.shape[2]):
        frame = np.asarray(image[:, :, f], dtype=np.float64)
        # Separable box filter, 'full', then MATLAB's 'same' crop, then decimate.
        tmp = np.apply_along_axis(lambda col: np.convolve(col, kern, mode="full"), 0, frame)
        tmp = np.apply_along_axis(lambda row: np.convolve(row, kern, mode="full"), 1, tmp)
        same = tmp[off : off + ypix, off : off + xpix]
        out.append(same[::bin_factor, ::bin_factor])

    stacked = np.stack(out, axis=2).astype(image.dtype, copy=False)
    return stacked[:, :, 0] if squeeze else stacked
